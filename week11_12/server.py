"""Week 12: FastAPI server for next-hour rain prediction.

Run `python train_model.py` first, then `python -m uvicorn server:app --reload`.
Interactive docs: http://127.0.0.1:8000/docs
"""

from functools import lru_cache
from pathlib import Path
from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, ConfigDict, Field

from shared import FEATURE_COLUMNS

MODEL_PATH = Path(__file__).resolve().parent / "models" / "weather_model.joblib"
app = FastAPI(
    title="Week 12 — Next-Hour Rain Prediction API",
    version="1.0.0",
    description="Predict whether the next hour has rain using current weather measurements."
)


class WeatherRequest(BaseModel):
    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    temperature_2m: float = Field(..., ge=-60, le=60, description="Air temperature in °C")
    relative_humidity_2m: float = Field(..., ge=0, le=100, description="Relative humidity (%)")
    cloud_cover: float = Field(..., ge=0, le=100, description="Cloud coverage (%)")
    wind_speed_10m: float = Field(..., ge=0, le=200, description="Wind speed at 10 m in km/h")


class WeatherPrediction(BaseModel):
    prediction: Literal["rain", "no_rain"]
    confidence: float = Field(..., ge=0, le=1)
    rain_probability: float = Field(..., ge=0, le=1)
    no_rain_probability: float = Field(..., ge=0, le=1)
    model: str
    target: str
    training_region: str


@lru_cache(maxsize=1)
def get_model_artifact() -> dict:
    if not MODEL_PATH.is_file():
        raise FileNotFoundError("No trained model. Run `python train_model.py` first.")
    # Only load the file generated by our local training script. Never load untrusted joblib files.
    return joblib.load(MODEL_PATH)


@app.get("/health")
def health():
    return {"status": "ready" if MODEL_PATH.is_file() else "model_missing", "model_file": MODEL_PATH.name}


@app.post("/predict", response_model=WeatherPrediction)
def predict(weather: WeatherRequest) -> WeatherPrediction:
    try:
        artifact = get_model_artifact()
        model = artifact["model"]
        metadata = artifact["metadata"]
        X = pd.DataFrame([weather.model_dump()])[FEATURE_COLUMNS]
        rain_class_index = list(model.classes_).index(1)
        rain_prob = float(model.predict_proba(X)[0, rain_class_index])
    except FileNotFoundError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc
    except (ValueError, KeyError, OSError) as exc:
        raise HTTPException(status_code=500, detail=f"Prediction failed: {exc}") from exc

    rain_prob = max(0.0, min(1.0, rain_prob))
    label = "rain" if rain_prob >= 0.5 else "no_rain"
    confidence = rain_prob if label == "rain" else 1 - rain_prob
    return WeatherPrediction(
        prediction=label,
        confidence=round(confidence, 4),
        rain_probability=round(rain_prob, 4),
        no_rain_probability=round(1 - rain_prob, 4),
        model=metadata.get("model", "RandomForestClassifier"),
        target=metadata.get("target", "rain during next hour"),
        training_region=metadata.get("trained_on", "Washington, DC"),
    )
